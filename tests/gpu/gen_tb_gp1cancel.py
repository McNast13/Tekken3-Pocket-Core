#!/usr/bin/env python3
"""Write tb_t3_gp1cancel.vhd for a core tree's gpu.vhd (the gpu entity has ~250 ports, most of them diagnostics, so the
port map is generated: every input without a default is tied off, the ones the test drives are named below).
usage: gen_tb_gp1cancel.py CORE_TREE OUT.vhd
Test (Tekken 3 GPU type, gpuType1 = 0):
  1. a GP0 quad (0x28) gets only 2 of its 5 words, so gpu_poly waits for parameters: GPUSTAT bit 26 must be 0
  2. GP1(01) (the game's per-frame reset): with t3_gp1cancel the command is cancelled and bit 26 returns to 1;
     without it bit 26 stays 0 (the freeze)
  3. a complete flat triangle (0x20) afterwards must draw and leave bit 26 at 1 (the GPU still works)
"""
import re
import sys

tree, out = sys.argv[1], sys.argv[2]
t = open(tree + "/rtl/gpu.vhd").read()
ent = re.search(r"^entity gpu is(.*?)^end entity", t, re.S | re.M).group(1)
named = {
    "clk1x": "clk1x", "clk2x": "clk2x", "clk2xIndex": "clk2xIndex", "clkvid": "clk1x", "ce": "'1'", "reset": "reset",
    "videoout_on": "'0'", "bus_addr": "bus_addr", "bus_dataWrite": "bus_dataWrite", "bus_write": "bus_write",
    "gpustat_out": "gstat", "t3_cancels": "cancels",
}
maps = []
has_cancels = False
for line in ent.split("\n"):
    m = re.match(r"\s*(\w+)\s*:\s*(in|out|inout)\s+([^;:]*?)(\s*:=.*?)?;?\s*(--.*)?$", line)
    if not m:
        continue
    name, mode, typ, default = m.group(1), m.group(2), m.group(3).strip(), m.group(4)
    if name == "t3_cancels":
        has_cancels = True
    if name in named:
        maps.append(f"      {name} => {named[name]}")
    elif mode == "in" and not default:
        zero = "'0'" if typ == "std_logic" else "(others => '0')"
        maps.append(f"      {name} => {zero}")
if not has_cancels:
    maps = [m for m in maps if "cancels" not in m]

tb = f"""-- generated by gen_tb_gp1cancel.py (see there)
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity tb_t3_gp1cancel is
end entity;

architecture sim of tb_t3_gp1cancel is
   signal clk1x, clk2x     : std_logic := '1';
   signal clk1xToggle      : std_logic := '0';
   signal clk1xToggle2x    : std_logic := '0';
   signal clk2xIndex       : std_logic := '0';
   signal reset            : std_logic := '1';
   signal bus_addr         : unsigned(3 downto 0) := (others => '0');
   signal bus_dataWrite    : std_logic_vector(31 downto 0) := (others => '0');
   signal bus_write        : std_logic := '0';
   signal gstat            : std_logic_vector(31 downto 0);
   signal cancels          : unsigned(15 downto 0) := (others => '0');
   signal done             : boolean := false;
begin
   clk1x <= not clk1x after 15 ns when not done;
   clk2x <= not clk2x after 7500 ps when not done;
   process (clk1x) begin if rising_edge(clk1x) then clk1xToggle <= not clk1xToggle; end if; end process;
   process (clk2x) begin
      if rising_edge(clk2x) then
         clk1xToggle2x <= clk1xToggle;
         clk2xIndex    <= '0';
         if (clk1xToggle2x = clk1xToggle) then clk2xIndex <= '1'; end if;
      end if;
   end process;

   igpu : entity work.gpu
   port map
   (
{(","+chr(10)).join(maps)}
   );

   stim : process
      procedure wr(a : integer; d : std_logic_vector(31 downto 0)) is
      begin
         wait until rising_edge(clk1x);
         bus_addr <= to_unsigned(a, 4); bus_dataWrite <= d; bus_write <= '1';
         wait until rising_edge(clk1x);
         bus_write <= '0';
         for i in 1 to 4 loop wait until rising_edge(clk1x); end loop;
      end procedure;
      procedure idle(n : integer) is
      begin
         for i in 1 to n loop wait until rising_edge(clk1x); end loop;
      end procedure;
      variable fails : integer := 0;
   begin
      idle(50); reset <= '0'; idle(2000);
      wr(4, x"00000000");                                   -- GP1(00) reset
      idle(200);
      wr(0, x"E3000000"); wr(0, x"E4077FFF"); wr(0, x"E5000000");   -- drawing area / offset
      idle(200);
      report "start: GPUSTAT=" & to_hstring(gstat);
      -- 0. control: a complete triangle before anything else (shows whether the testbench's VRAM model lets drawing end)
      wr(0, x"20FF0000"); wr(0, x"000A000A"); wr(0, x"000A0032"); wr(0, x"0032000A");
      idle(40000);
      report "control triangle: GPUSTAT=" & to_hstring(gstat) & " bit26=" & std_logic'image(gstat(26)) &
             " proc_idle=" & std_logic'image(<<signal .tb_t3_gp1cancel.igpu.proc_idle : std_logic>>) &
             " pipeline_busy=" & std_logic'image(<<signal .tb_t3_gp1cancel.igpu.pipeline_busy : std_logic>>) &
             " pipeline_stall=" & std_logic'image(<<signal .tb_t3_gp1cancel.igpu.pipeline_stall : std_logic>>) &
             " fifoOut_Empty=" & std_logic'image(<<signal .tb_t3_gp1cancel.igpu.fifoOut_Empty : std_logic>>) &
             " poly_reqVRAMEnable=" & std_logic'image(<<signal .tb_t3_gp1cancel.igpu.poly_reqVRAMEnable : std_logic>>) &
             " poly_requestFifo=" & std_logic'image(<<signal .tb_t3_gp1cancel.igpu.poly_requestFifo : std_logic>>) &
             " poly_state=" & to_hstring(<<signal .tb_t3_gp1cancel.igpu.poly_dbg_state : std_logic_vector(4 downto 0)>>);
      if gstat(26) /= '1' then report "FAIL: control triangle did not finish (testbench VRAM model?)" severity error; fails := fails + 1; end if;
      -- 1. half a quad
      wr(0, x"28808080"); wr(0, x"00100010");
      idle(3000);
      report "half quad: GPUSTAT=" & to_hstring(gstat) & " bit26=" & std_logic'image(gstat(26));
      if gstat(26) /= '0' then report "FAIL: GPU should be waiting for the quad's parameters" severity error; fails := fails + 1; end if;
      -- 2. the game's per-frame GP1(01)
      wr(4, x"01000000");
      idle(3000);
      report "after GP1(01): GPUSTAT=" & to_hstring(gstat) & " bit26=" & std_logic'image(gstat(26)) & " cancels=" & integer'image(to_integer(cancels));
      if gstat(26) /= '1' then report "FAIL: GPU still not ready after GP1(01) (the Tekken 3 freeze)" severity error; fails := fails + 1; end if;
      -- 3. a complete flat triangle must still draw
      wr(0, x"20FF0000"); wr(0, x"000A000A"); wr(0, x"000A0032"); wr(0, x"0032000A");
      idle(40000);
      report "after triangle: GPUSTAT=" & to_hstring(gstat) & " bit26=" & std_logic'image(gstat(26));
      if gstat(26) /= '1' then report "FAIL: GPU not ready after a complete triangle" severity error; fails := fails + 1; end if;
      report "tb_t3_gp1cancel: " & integer'image(fails) & " failures";
      done <= true;
      wait;
   end process;
end architecture;
"""
open(out, "w").write(tb)
print("wrote", out, "(t3_cancels port present)" if has_cancels else "(no t3_cancels port)")
